  static ChinaCity? match(String value) {
    final parts = value
        .split('·')
        .map((item) => item.trim())
        .where((item) => item.isNotEmpty)
        .toList();
    if (parts.isEmpty) return null;
    final province = parts.length > 1 ? parts.first : null;
    final city = parts.last.replaceFirst(RegExp(r'市$'), '');
    for (final item in all) {
      if (item.name != city) continue;
      if (province == null || item.province == province) return item;
    }
    return null;
  }

  static List<ChinaCity> search(String query) {
    final normalized = query.trim().toLowerCase();
    if (normalized.isEmpty) return all;
    return all
        .where(
          (item) =>
              item.name.toLowerCase().contains(normalized) ||
              item.province.toLowerCase().contains(normalized) ||
              item.value.toLowerCase().contains(normalized),
        )
        .toList(growable: false);
  }
